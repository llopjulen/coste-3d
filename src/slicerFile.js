/* ==================================================================
   SLICED FILE READER
   Reads the file a slicer exports and pulls out the two numbers the
   calculator needs: print time and grams of filament.

   Every slicer writes them as comments inside the G-code, but each
   one with its own wording, so each pattern below says which slicer
   it is for. The file is read inside the browser: nothing is uploaded.
================================================================== */

// The comments live at the very top (Bambu Studio, OrcaSlicer, Cura)
// or at the very bottom (PrusaSlicer). Reading the first and the last
// megabyte is enough, and keeps a 200 MB file from freezing the page.
const CHUNK = 1024 * 1024

// Only used when a file gives filament length but no grams (Cura).
const DEFAULT_DENSITY = 1.24 // g/cm³, PLA
const DEFAULT_DIAMETER = 1.75 // mm

const SECONDS_PER_HOUR = 3600

/* An error whose message is written for the person using the app. */
export class ImportError extends Error {}

/* ---------------------------- Small helpers ----------------------- */

const toNumber = (s) => {
  if (s == null) return null
  const n = parseFloat(s)
  return Number.isFinite(n) ? n : null
}
const splitList = (s) => (s ?? '').split(/[,;]/).map(x => x.trim()).filter(Boolean)
const numbers = (s) => splitList(s).map(parseFloat).filter(Number.isFinite)
const sum = (list) => list.reduce((a, b) => a + b, 0)
const round = (n, decimals) => Math.round(n * 10 ** decimals) / 10 ** decimals

/* First captured group of a pattern, or null if it isn't there. */
function grab(text, pattern) {
  const m = text.match(pattern)
  return m ? m[1].trim() : null
}

/* The list of a "filament used [g] = 9.36, 9.63" style line, skipping
   the "total filament used [g]" line that contains the same words. */
function perFilament(text, unit) {
  const pattern = new RegExp(`(total )?filament used \\[${unit}\\]\\s*=\\s*([^\\n\\r]+)`, 'gi')
  for (const m of text.matchAll(pattern)) {
    if (!m[1]) return numbers(m[2])
  }
  return []
}

/* "1d 2h 3m 4s", "1h 56m 9s" or "13m 53s"  ->  seconds */
export function parseDuration(text) {
  if (!text) return null
  const unit = { d: 86400, h: 3600, m: 60, s: 1 }
  let total = 0
  let found = false
  for (const [, value, u] of text.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])(?![a-z])/gi)) {
    total += parseFloat(value) * unit[u.toLowerCase()]
    found = true
  }
  return found ? total : null
}

/* Which slicer wrote the file, only to show it in the summary. */
function detectSlicer(text) {
  const generatedBy = text.match(/generated by (\S+) (\S+) on /) // PrusaSlicer, OrcaSlicer
  if (generatedBy) return `${generatedBy[1]} ${generatedBy[2]}`
  const bambu = grab(text, /;\s*BambuStudio\S*\s+([\d.]+)/)
  if (bambu) return `Bambu Studio ${bambu}`
  const cura = grab(text, /Cura_SteamEngine\s+([\d.]+)/)
  if (cura) return `Cura ${cura}`
  const producer = grab(text, /Producer=([^\n\r]+)/) // PrusaSlicer binary G-code
  if (producer) return producer
  return null
}

/* ==================================================================
   G-CODE TEXT  ->  { slicer, seconds, totalGrams, purgeGrams,
                      filaments: [{ type, color, grams }], estimated }
   Returns null if the text has neither a time nor a weight.
================================================================== */
export function parseSlicerText(text) {
  /* ---- Print time ---- */
  let seconds =
    // Bambu Studio / OrcaSlicer header: "; model printing time: 1h 49m 51s; total estimated time: 1h 56m 9s"
    parseDuration(grab(text, /total estimated time:\s*([^;\n\r]+)/i)) ??
    // PrusaSlicer / OrcaSlicer (also the binary .bgcode): "estimated printing time (normal mode) = 1h 14m 3s"
    parseDuration(grab(text, /estimated printing time \(normal mode\)\s*=\s*([^\n\r]+)/i))
  if (seconds == null) {
    // Cura: ";TIME:5025" in seconds (";PRINT.TIME:" on Ultimaker printers)
    const cura = [...text.matchAll(/^;(?:PRINT\.)?TIME:(\d+(?:\.\d+)?)/gm)].map(m => parseFloat(m[1]))
    if (cura.length) seconds = Math.max(...cura)
  }

  /* ---- Filament type, colour and density, when the slicer lists them ---- */
  const types = splitList(grab(text, /(?:^|\n)[;\s]*filament_type\s*[=:]\s*([^\n\r]+)/))
  const colors = splitList(grab(text, /(?:^|\n)[;\s]*filament_colou?r\s*[=:]\s*([^\n\r]+)/))
  const densities = numbers(grab(text, /filament_density\s*[=:]\s*([^\n\r]+)/i))
  const densityOf = (i) => densities[i] || densities[0] || DEFAULT_DENSITY

  /* ---- Grams ---- */
  let estimated = false
  // PrusaSlicer / OrcaSlicer: "filament used [g] = 9.36, 9.63" (one number per filament)
  let grams = perFilament(text, 'g')
  // Cura, when the printer profile writes it: ";Filament weight = [12.3, 4.5]"
  if (!sum(grams)) grams = numbers(grab(text, /;Filament weight\s*=\s*\[([^\]]+)\]/i))
  // Only cm³ given (density was left at 0 in the profile)
  if (!sum(grams)) {
    const cm3 = perFilament(text, 'cm3')
    if (sum(cm3)) {
      grams = cm3.map((v, i) => v * densityOf(i))
      estimated = densities.length === 0
    }
  }
  // Cura: ";Filament used: 1.49416m, 0.5m" — metres of 1.75 mm filament
  if (!sum(grams)) {
    const metres = numbers(grab(text, /^;Filament used:\s*([^\n\r]+)/m)?.replace(/m/g, ''))
    if (sum(metres)) {
      const area = Math.PI * (DEFAULT_DIAMETER / 2) ** 2 // mm²
      grams = metres.map((m, i) => (m * 1000 * area / 1000) * densityOf(i))
      estimated = true
    }
  }

  const totalGrams =
    // PrusaSlicer / OrcaSlicer: "total filament used [g] = 18.99"
    toNumber(grab(text, /total filament used \[g\]\s*=\s*([\d.]+)/i)) ||
    // Bambu Studio / OrcaSlicer header: "; total filament weight [g] : 32.60"
    toNumber(grab(text, /total filament weight \[g\]\s*:\s*([\d.]+)/i)) ||
    (sum(grams) > 0 ? sum(grams) : null)

  /* ---- Purge: PrusaSlicer says how much went to the wipe tower ---- */
  // 0 means "known to be zero" (single colour); null means "not listed".
  const purgeGrams = toNumber(grab(text, /total filament used for wipe tower \[g\]\s*=\s*([\d.]+)/i))

  if (seconds == null && totalGrams == null) return null

  // One entry per filament, matching grams with type and colour by order.
  const count = Math.max(grams.length, types.length > 1 ? types.length : 0)
  const filaments = count > 0
    ? Array.from({ length: count }, (_, i) => ({
        type: types[i] || types[0] || '',
        color: colors[i] || '',
        grams: grams[i] ?? (count === 1 ? totalGrams ?? 0 : 0),
      })).filter(f => f.grams > 0)
    : []

  return {
    slicer: detectSlicer(text),
    seconds,
    totalGrams,
    purgeGrams,
    filaments,
    estimated,
  }
}

/* ==================================================================
   BAMBU STUDIO / ORCASLICER SLICED 3MF
   A .gcode.3mf is a zip. Inside, Metadata/slice_info.config lists
   every sliced plate with its time ("prediction", in seconds), its
   weight and the grams of each filament.
================================================================== */
export function parseSliceInfo(xml) {
  const plates = []
  for (const [, body] of xml.matchAll(/<plate>([\s\S]*?)<\/plate>/g)) {
    const meta = {}
    for (const [, key, value] of body.matchAll(/<metadata\s+key="([^"]*)"\s+value="([^"]*)"/g)) {
      meta[key] = value
    }
    const filaments = [...body.matchAll(/<filament\b([^>]*?)\/?>/g)].map(([, attrs]) => {
      const a = Object.fromEntries([...attrs.matchAll(/([\w-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]))
      return { type: a.type || '', color: a.color || '', grams: toNumber(a.used_g) ?? 0 }
    }).filter(f => f.grams > 0)

    // OrcaSlicer leaves "weight" empty when the profile has no density:
    // then the grams of each filament are added up instead.
    const weight = toNumber(meta.weight)
    const fromFilaments = sum(filaments.map(f => f.grams))
    plates.push({
      index: parseInt(meta.index, 10) || plates.length + 1,
      seconds: toNumber(meta.prediction) || null,
      totalGrams: weight > 0 ? weight : (fromFilaments > 0 ? fromFilaments : null),
      purgeGrams: null,
      filaments,
      estimated: false,
    })
  }
  return plates
}

/* ==================================================================
   NUMBERS FOR THE FORM
   choice: a plate number, or 'all' to add every plate up.
   parts:  how many parts are on that plate, to get one part's share.
================================================================== */
export function formValuesFromPlates(plates, choice, parts) {
  const chosen = choice === 'all' ? plates : plates.filter(p => p.index === choice)
  const n = Math.max(1, Math.floor(parts) || 1)
  const values = {}

  if (chosen.length && chosen.every(p => p.seconds != null)) {
    values.hours = round(sum(chosen.map(p => p.seconds)) / SECONDS_PER_HOUR / n, 2)
  }
  if (chosen.length && chosen.every(p => p.totalGrams != null)) {
    const total = sum(chosen.map(p => p.totalGrams))
    // When the file doesn't split out the purge, it's already inside the
    // total, so purge goes to 0 to avoid counting it twice.
    const purge = sum(chosen.map(p => p.purgeGrams ?? 0))
    values.partGrams = round(Math.max(total - purge, 0) / n, 1)
    values.purgeGrams = round(purge / n, 1)
  }
  return values
}

/* ==================================================================
   READ A FILE CHOSEN OR DROPPED BY THE PERSON
   Returns { fileName, slicer, plates: [{ index, seconds, totalGrams,
   purgeGrams, filaments, estimated }] } or throws an ImportError.
================================================================== */
export async function readSlicedFile(file) {
  const name = file.name.toLowerCase()

  if (/\.(stl|obj|step|stp|amf)$/.test(name)) {
    throw new ImportError(
      "This is a 3D model, not a sliced file. Slice it first, then drop the G-code or the sliced 3MF (.gcode.3mf)."
    )
  }
  if (name.endsWith('.3mf')) return read3mf(file)

  // .gcode, .gco, .g, .bgcode... anything else is read as G-code text.
  const result = parseSlicerText(await readEnds(file))
  if (!result) {
    throw new ImportError(
      "Couldn't find a print time or filament weight in this file. Make sure it's the G-code your slicer exported, or type the numbers in by hand."
    )
  }
  const { slicer, ...plate } = result
  return { fileName: file.name, slicer, plates: [{ index: 1, ...plate }] }
}

/* The first and last megabyte of a big file, or all of a small one. */
async function readEnds(file) {
  if (file.size <= CHUNK * 2) return file.text()
  const head = await file.slice(0, CHUNK).text()
  const tail = await file.slice(file.size - CHUNK).text()
  return `${head}\n${tail}`
}

async function read3mf(file) {
  // The unzip library is only downloaded when someone drops a 3MF.
  const { unzipSync, strFromU8 } = await import('fflate')
  const data = new Uint8Array(await file.arrayBuffer())

  // Unzip only the entries we ask for, not the whole 3D model.
  const open = (wanted) => {
    try {
      return unzipSync(data, { filter: entry => wanted(entry.name) })
    } catch {
      throw new ImportError("This 3MF looks damaged. Try exporting it again from your slicer.")
    }
  }

  const info = open(n => n === 'Metadata/slice_info.config')['Metadata/slice_info.config']
  let plates = info ? parseSliceInfo(strFromU8(info)) : []
  let slicer = null

  // No slice info, or a plate without numbers: read the plate's G-code.
  const missing = plates.length === 0 || plates.some(p => p.seconds == null || p.totalGrams == null)
  if (missing) {
    const gcodes = open(n => /^Metadata\/plate_\d+\.gcode$/.test(n))
    const plateNumber = (n) => parseInt(n.match(/plate_(\d+)/)[1], 10)
    const fromGcode = Object.keys(gcodes)
      .sort((a, b) => plateNumber(a) - plateNumber(b))
      .map(entry => {
        const bytes = gcodes[entry]
        const text = bytes.length > CHUNK * 2
          ? `${strFromU8(bytes.subarray(0, CHUNK))}\n${strFromU8(bytes.subarray(bytes.length - CHUNK))}`
          : strFromU8(bytes)
        const parsed = parseSlicerText(text)
        return parsed && { index: plateNumber(entry), ...parsed }
      })
      .filter(Boolean)

    if (plates.length === 0) {
      plates = fromGcode.map(({ slicer: _slicer, ...plate }) => plate)
    } else {
      // Fill the gaps of each plate with what its G-code says.
      plates = plates.map(p => {
        const g = fromGcode.find(x => x.index === p.index)
        if (!g) return p
        return {
          ...p,
          seconds: p.seconds ?? g.seconds,
          totalGrams: p.totalGrams ?? g.totalGrams,
          purgeGrams: p.purgeGrams ?? g.purgeGrams,
          filaments: p.filaments.length ? p.filaments : g.filaments,
          estimated: p.totalGrams == null ? g.estimated : p.estimated,
        }
      })
    }
    slicer = fromGcode.find(g => g.slicer)?.slicer ?? null
  }

  if (plates.length === 0) {
    throw new ImportError(
      "This 3MF is a project that hasn't been sliced. Slice it in Bambu Studio or OrcaSlicer and export the plate as a sliced file (.gcode.3mf), or export the G-code."
    )
  }
  return { fileName: file.name, slicer: slicer ?? 'Bambu Studio / OrcaSlicer', plates }
}
